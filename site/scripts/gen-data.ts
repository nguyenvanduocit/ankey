// Copies the syllable and English word lists out of the Swift engine, so the site demo reads the same data as the app.
//   bun run gen
import { readFileSync, writeFileSync } from "node:fs"

const core = new URL("../../Core/", import.meta.url)

function literal(file: string, name: string): string {
  const swift = readFileSync(new URL(file, core), "utf8")
  const match = swift.match(new RegExp(`(?:private )?let ${name} = """\\n([\\s\\S]*?)\\n"""`))
  if (!match) throw new Error(`${name} not found in ${file}`)
  return match[1].split(/\s+/).filter(Boolean).join(" ")
}

const data = {
  syllables: literal("Syllables.swift", "source"),
  always: literal("English.swift", "alwaysSource"),
  context: literal("English.swift", "contextSource"),
  known: literal("English.swift", "knownSource"),
}

const out = `// Generated by scripts/gen-data.ts from Core/Syllables.swift and Core/English.swift. Do not edit.\n${Object.entries(data)
  .map(([key, value]) => `export const ${key} = ${JSON.stringify(value)}\n`)
  .join("")}`
writeFileSync(new URL("../public/engine-data.js", import.meta.url), out)
