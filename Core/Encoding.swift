import Foundation

/// How a finished Vietnamese word is written into the document.
///
/// The legacy encodings are bytes that a legacy font draws as Vietnamese letters. An input
/// method can only insert Unicode text, so each byte goes in as the Unicode scalar with the
/// same value (Latin-1). The text reads right only in a font made for that encoding.
enum OutputEncoding: String, CaseIterable {
    /// Precomposed Unicode, the text as the engine makes it.
    case unicode
    /// TCVN3 (ABC): one byte per letter, for fonts like .VnTime.
    case tcvn3
    /// VNI Windows: a base letter plus a mark byte for most letters, for fonts like VNI-Times.
    case vniWindows

    /// Letters the encoding has no code for, and everything that is not Vietnamese, stay as they are.
    func convert(_ text: String) -> String {
        if self == .unicode { return text }
        let table = self.table
        var out = String.UnicodeScalarView()
        for character in text {
            if let bytes = table[character] {
                out.append(contentsOf: bytes.map { Unicode.Scalar($0) })
            } else {
                out.append(contentsOf: character.unicodeScalars)
            }
        }
        return String(out)
    }

    /// What is left of `text` once the app deletes the last character of its encoded form. A VNI letter with a
    /// mark is two characters there, and only the mark goes.
    func erasingLast(_ text: String) -> String {
        guard let last = text.last else { return text }
        var left = String(text.dropLast())
        let table = self.table
        guard let bytes = table[last], bytes.count > 1 else { return left }
        let rest = Array(bytes.dropLast())
        if let letter = table.first(where: { $0.value == rest })?.key {
            left.append(letter)
        } else {
            left.unicodeScalars.append(contentsOf: rest.map { Unicode.Scalar($0) })
        }
        return left
    }

